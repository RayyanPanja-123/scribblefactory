"""Writes docs/missing-fragments/capabilities.json: what the engine and planner can do, read from the code itself, plus
the known limits (LIMITS below: edit them when a limit is lifted or found). The story-writing AI reads this file so it
never stages something the engine cannot show (docs/missing-fragments/01-capability-manifest.md).

  .venv/Scripts/python scripts/capabilities.py          write the file
  .venv/Scripts/python scripts/capabilities.py --check  exit 1 when the file is out of date (for a test or a hook)
"""
import json
import sys
from pathlib import Path
from typing import get_args

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
OUT = ROOT / "docs" / "missing-fragments" / "capabilities.json"

from pipeline.scribble.schemas import ACTIONS, BUILTIN_CREATURES, BUILTIN_SETS, BUILTIN_WARDROBE  # noqa: E402
from pipeline.scribble.schemas.library import ITEM_ACTIONS, WeatherKind  # noqa: E402
from pipeline.scribble.schemas.series import Expression  # noqa: E402
from pipeline.scribble.schemas.story import CamAngle, CamMove  # noqa: E402
from pipeline.scribble.stages.prep import FX_MODES, MAX_LIGHTNING  # noqa: E402
from pipeline.scribble.stages.shots import MAX_ON_STAGE  # noqa: E402

# Known limits, plainly: what a story must not ask for (or must ask for another way). One line each, newest last.
# status: "workaround" = say it differently; "open" = needs engine work (see docs/missing-fragments/gap-log.md).
LIMITS = [
    {"id": "flat-ground", "status": "partly lifted", "limit": "characters walk on flat ground; stairs and slopes only along a set's `trail` (`@do <cast>: climb`), one trail per set",
     "workaround": "put the stairs in a set with a trail; cut between levels for anything else"},
    {"id": "no-swimming", "status": "open", "limit": "no swimming, diving or flying: no free vertical movement, no depth, no underwater look",
     "workaround": "a water set (`water: true`) with characters standing, or cut to the surface; see 02-locomotion-modes.md"},
    {"id": "no-battle-structure", "status": "open", "limit": "no duel or battle choreography: one aimed custom action per attacker (`attack-with-spears <target>`), no parry, hit exchange or formation",
     "workaround": "two or three short lines, one strike each, victim reacts (`collapse` + `dead`); crowds fight with `@crowd <group> fight <other>`; see 03-interaction-choreography.md"},
    {"id": "one-action-per-line", "status": "workaround", "limit": "each cast member has one action per narration line (a long line is split into shots, an action happens in the first)",
     "workaround": "one beat per line; use `@do` on the line the beat happens"},
    {"id": "stage-size", "status": "workaround", "limit": f"at most {MAX_ON_STAGE} in the front row and 12 on stage; walking needs free room",
     "workaround": "split the scene; use in-place actions with four or more on stage"},
    {"id": "own-art-only", "status": "workaround", "limit": "characters are the stickman rig only (humanoid, biped, bird, quadruped, crawler); no new body shapes without a library creature",
     "workaround": "add a creature to the library"},
    {"id": "no-collision", "status": "workaround", "limit": "characters do not collide: two climbing the same trail, or one walking through another, overlap",
     "workaround": "keep climbs and walks to one character at a time"},
    {"id": "camera-orbit-cap", "status": "workaround", "limit": "orbit arcs at most 45 degrees (the painted backdrop shows its edges beyond that)",
     "workaround": "chain an orbit with a cut"},
    {"id": "voice-locked", "status": "workaround", "limit": "narration words and timing are fixed once the voice is recorded: no new lines, `@pause` or `@pace` after",
     "workaround": "direct with `@do` / `@face` / `@cam` only"},
]


def manifest() -> dict:
    return {
        "note": "generated by scripts/capabilities.py from the code: do not edit by hand (edit LIMITS in the script)",
        "actions": {a: sorted(t) for a, t in sorted(ACTIONS.items())},
        "item_actions": sorted(ITEM_ACTIONS),
        "camera": {"angles": list(get_args(CamAngle)), "moves": [*get_args(CamMove), "hold"], "orbit_max_degrees": 45},
        "expressions": list(get_args(Expression)),
        "weather": ["clear", *get_args(WeatherKind)],
        "moods": ["tense", "dark", "flashback", "bright", "off"],
        "caption_fx": list(FX_MODES), "max_lightning_per_part": MAX_LIGHTNING,
        "sets_builtin": dict(BUILTIN_SETS), "creatures_builtin": sorted(BUILTIN_CREATURES), "wardrobe_builtin": dict(BUILTIN_WARDROBE),
        "stage": {"max_front_row": MAX_ON_STAGE, "max_cast": 12},
        "limits": LIMITS,
    }


if __name__ == "__main__":
    text = json.dumps(manifest(), indent=2, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
